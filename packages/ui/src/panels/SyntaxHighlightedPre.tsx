import { Check, Terminal } from "lucide-react"
import type React from "react"
import { useEffect, useMemo, useRef, useState } from "react"

import {
  bunColorCss,
  formatSyntaxAsBunTerminalAnsi,
  SYNTAX_TOKEN_PALETTE,
  type SyntaxFormat,
  type SyntaxTokenType,
  tokenizeSyntax,
} from "@sportsdesk-ops/contracts"

import { renderAnsiReact } from "../ansi.tsx"
import { copyText } from "../clipboard.ts"

const MONO_FONT =
  'ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, "Liberation Mono", monospace'

export interface SyntaxHighlightedPreProps extends Omit<
  React.HTMLAttributes<HTMLPreElement>,
  "children"
> {
  readonly text: string
  readonly format: SyntaxFormat
  /**
   * - `"tokens"` (default): renders semantic React `<span data-syntax-token="...">` styled with
   *   `Bun.color`-resolved hex tokens.
   * - `"ansi"`: renders 24-bit TrueColor ANSI SGR generated by `formatSyntaxAsBunTerminalAnsi()`
   *   through `renderAnsiReact()` for exact `Bun.Terminal` PTY visual parity.
   */
  readonly renderMode?: "tokens" | "ansi" | undefined
}

const LEGEND_ORDER: readonly SyntaxTokenType[] = ["key", "string", "number", "boolean"]

/**
 * Compact inline token legend showing Keys, Strings, Numbers, and Booleans with both color
 * indicators and explicit text labels.
 */
export function SyntaxTokenLegend({
  compact = false,
}: {
  readonly compact?: boolean | undefined
}): React.ReactElement {
  return (
    <span
      data-syntax-legend="true"
      aria-label="Syntax highlight legend: Keys, Strings, Numbers, Booleans"
      style={{
        display: "inline-flex",
        alignItems: "center",
        flexWrap: "wrap",
        gap: compact ? "8px" : "10px",
        fontSize: compact ? "10.5px" : "11px",
        fontFamily: MONO_FONT,
        color: "var(--text-muted, #94a3b8)",
      }}
    >
      {LEGEND_ORDER.map((tokenType) => {
        const spec = SYNTAX_TOKEN_PALETTE[tokenType]
        const color = bunColorCss(spec.hex)
        return (
          <span
            key={tokenType}
            data-syntax-legend-token={tokenType}
            style={{
              display: "inline-flex",
              alignItems: "center",
              gap: "4px",
              whiteSpace: "nowrap",
            }}
          >
            <span
              aria-hidden="true"
              style={{
                width: "7px",
                height: "7px",
                borderRadius: "2px",
                backgroundColor: color,
                display: "inline-block",
                flexShrink: 0,
              }}
            />
            <span style={{ color, fontWeight: spec.bold ? 600 : 500 }}>{spec.label}</span>
          </span>
        )
      })}
    </span>
  )
}

/**
 * Copy button that serializes the preformatted block into 24-bit TrueColor ANSI escape sequences
 * (`Bun.color(..., "ansi-16m")`) ready for `Bun.Terminal`.
 */
export function CopyBunTerminalAnsiButton({
  text,
  format,
  compact = false,
}: {
  readonly text: string
  readonly format: SyntaxFormat
  readonly compact?: boolean | undefined
}): React.ReactElement {
  const [copied, setCopied] = useState(false)
  const timerRef = useRef<ReturnType<typeof setTimeout> | null>(null)

  useEffect(() => {
    return () => {
      if (timerRef.current !== null) clearTimeout(timerRef.current)
    }
  }, [])

  const handleCopy = () => {
    const ansi = formatSyntaxAsBunTerminalAnsi(text, format)
    void copyText(ansi).then((res) => {
      if (!res.ok) return
      setCopied(true)
      if (timerRef.current !== null) clearTimeout(timerRef.current)
      timerRef.current = setTimeout(() => setCopied(false), 1800)
    })
  }

  return (
    <button
      type="button"
      data-copy-bun-terminal-ansi="true"
      onClick={handleCopy}
      title="Copy 24-bit TrueColor ANSI output (Bun.color ansi-16m) for Bun.Terminal PTY"
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: "4px",
        padding: compact ? "3px 8px" : "5px 10px",
        borderRadius: "5px",
        borderWidth: "1px",
        borderStyle: "solid",
        borderColor: copied ? "rgba(74, 222, 128, 0.55)" : "var(--border-strong, #334155)",
        backgroundColor: copied ? "rgba(34, 197, 94, 0.12)" : "rgba(15, 23, 42, 0.7)",
        color: copied ? "#86efac" : "#cbd5e1",
        fontSize: compact ? "11px" : "11.5px",
        fontWeight: 600,
        cursor: "pointer",
        whiteSpace: "nowrap",
      }}
    >
      {copied ? <Check size={11} aria-hidden="true" /> : <Terminal size={11} aria-hidden="true" />}
      <span>{copied ? "ANSI Copied" : "Copy ANSI (Bun.Terminal)"}</span>
    </button>
  )
}

/**
 * Direct `<pre>` syntax-highlighted output block using Bun Utilities API (`Bun.color`) tokens or
 * 24-bit TrueColor `Bun.Terminal` ANSI rendering.
 */
export function SyntaxHighlightedPre({
  text,
  format,
  renderMode = "tokens",
  style,
  className,
  ...rest
}: SyntaxHighlightedPreProps): React.ReactElement {
  const renderedContent = useMemo<React.ReactNode>(() => {
    if (renderMode === "ansi") {
      return renderAnsiReact(formatSyntaxAsBunTerminalAnsi(text, format))
    }
    const tokens = tokenizeSyntax(text, format)
    return tokens.map((tok, idx) => {
      if (tok.type === "plain") {
        return <span key={idx}>{tok.value}</span>
      }
      const spec = SYNTAX_TOKEN_PALETTE[tok.type]
      const tokenStyle: React.CSSProperties = {
        color: bunColorCss(spec.hex),
      }
      if (spec.bold) tokenStyle.fontWeight = 600
      if (spec.italic) tokenStyle.fontStyle = "italic"
      if (spec.tabularNums) tokenStyle.fontVariantNumeric = "tabular-nums"
      return (
        <span key={idx} data-syntax-token={tok.type} style={tokenStyle}>
          {tok.value}
        </span>
      )
    })
  }, [text, format, renderMode])

  return (
    <pre
      {...rest}
      className={className ? `sd-syntax-pre ${className}` : "sd-syntax-pre"}
      data-syntax-pre="true"
      data-syntax-format={format}
      data-syntax-render-mode={renderMode}
      style={{
        fontFamily: MONO_FONT,
        ...style,
      }}
    >
      {renderedContent}
    </pre>
  )
}
